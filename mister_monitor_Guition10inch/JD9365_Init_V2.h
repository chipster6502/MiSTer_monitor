// =============================================================================
//  JD9365_Init_V2.h -- init table for the second Guition panel revision
//
//  Guition ships the JC8012P4A1C with two different LCD panels behind the same
//  JD9365 driver chip. Units from batch 2624 onward carry the newer panel; the
//  batch number is the figure in parentheses after the SKU on the back sticker.
//  Driving one panel with the other's init sequence and timings produces
//  horizontal banding across the screen while every init call still reports
//  success -- the bus comes up, only the picture is wrong.
//
//  Because both revisions use the same controller, they cannot be told apart at
//  runtime: the panel ID reads back identically. The revision has to be chosen
//  by the user.
//
//  The sequence below is taken from ESPHome's JC8012P4A1-V2 model
//  (esphome/components/mipi_dsi/models/guition.py, GPL-3.0), contributed by
//  rayz90 in esphome/esphome#17457, who extracted it from Guition's own
//  reference driver for this panel. The two per-command delays are ours: the
//  ESPHome list carries none because their component applies its own after
//  sleep-out, whereas this driver takes the delay from the table.
//
//  Timings differ from revision 1 as well, and are applied in Panel_JD9365.hpp:
//      DPI clock          60 MHz -> 70 MHz
//      vsync_back_porch        8 -> 10
//      (lane bit rate stays at 1500 Mbps; hsync timings are unchanged)
// =============================================================================

